"""Generates the teleop wire codecs from Configs/schema/stream.json:
Sources/MotionIO/StreamMessages.swift and python/retargeter_client/messages.py."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
schema = json.load(open(os.path.join(ROOT, "Configs/schema/stream.json")))
VERSION = schema["version"]

SWIFT_SCALAR = {"u8": "UInt8", "u16": "UInt16", "u32": "UInt32", "u64": "UInt64", "i32": "Int32",
                "f32": "Float", "f64": "Double", "str": "String"}
PY_STRUCT = {"u8": "B", "u16": "H", "u32": "I", "u64": "Q", "i32": "i", "f32": "f", "f64": "d"}
NP_DTYPE = {"u8": "<u1", "i32": "<i4", "f32": "<f4", "f64": "<f8", "u32": "<u4"}


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(p.capitalize() for p in rest)


def fields(m):
    return [(f[0], f[1], f[2] if len(f) > 2 else "") for f in m["fields"]]


def swift():
    out = ["// Generated by tools/gen_stream_codec.py from Configs/schema/stream.json — do not edit.",
           "// " + schema["comment"], "", "public enum StreamWire {",
           "    public static let magic: UInt32 = 0x5347_5452   // 'RTGS'",
           f"    public static let version: UInt16 = {VERSION}", "    public static let headerSize = 12", "}", ""]
    for m in schema["messages"]:
        out.append(f"/// {m['doc']}")
        out.append(f"public struct {m['name']}: Sendable, Equatable {{")
        out.append(f"    public static let type: UInt16 = {m['type']}")
        for name, t, doc in fields(m):
            st = f"[{SWIFT_SCALAR[t[:-2]]}]" if t.endswith("[]") else SWIFT_SCALAR[t]
            out.append(f"    public var {camel(name)}: {st}" + (f"   // {doc}" if doc else ""))
        args = ", ".join(f"{camel(n)}: " + (f"[{SWIFT_SCALAR[t[:-2]]}]" if t.endswith("[]") else SWIFT_SCALAR[t])
                         for n, t, _ in fields(m))
        out.append("")
        out.append(f"    public init({args}) {{")
        for n, _, _ in fields(m):
            out.append(f"        self.{camel(n)} = {camel(n)}")
        out.append("    }")
        out.append("")
        out.append("    public func encode() -> [UInt8] {")
        out.append("        var w = WireWriter(type: Self.type)")
        for n, t, _ in fields(m):
            out.append(f"        w.put({camel(n)})")
        out.append("        return w.finish()")
        out.append("    }")
        out.append("")
        out.append("    /// `payload`: the bytes after the header.")
        out.append("    public init(payload r: inout WireReader) throws {")
        for n, t, _ in fields(m):
            out.append(f"        {camel(n)} = try r.get()")
        out.append("    }")
        out.append("}")
        out.append("")
    out.append("public enum StreamMessage: Sendable, Equatable {")
    for m in schema["messages"]:
        out.append(f"    case {camel(m['name'][0].lower() + m['name'][1:])}({m['name']})")
    out.append("")
    out.append("    /// Decodes one message (header + payload).")
    out.append("    public static func decode(_ bytes: [UInt8]) throws -> StreamMessage {")
    out.append("        var r = try WireReader(message: bytes)")
    out.append("        switch r.type {")
    for m in schema["messages"]:
        case = camel(m['name'][0].lower() + m['name'][1:])
        out.append(f"        case {m['name']}.type: let m = try {m['name']}(payload: &r); try r.finish(); return .{case}(m)")
    out.append("        default: throw WireError(message: \"unknown message type \\(r.type)\")")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    public func encode() -> [UInt8] {")
    out.append("        switch self {")
    for m in schema["messages"]:
        case = camel(m['name'][0].lower() + m['name'][1:])
        out.append(f"        case .{case}(let m): return m.encode()")
    out.append("        }")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def python():
    out = ['"""Generated by tools/gen_stream_codec.py from Configs/schema/stream.json - do not edit.',
           "", schema["comment"], '"""', "", "from __future__ import annotations", "",
           "import struct", "from dataclasses import dataclass, field", "", "import numpy as np", "",
           "MAGIC = 0x53475452  # 'RTGS'", f"VERSION = {VERSION}", "HEADER = struct.Struct('<IHHI')", "", "",
           "class WireError(ValueError):", "    pass", "", "",
           "def _put(buf: bytearray, kind: str, value) -> None:",
           "    if kind == 'str':",
           "        data = value.encode('utf-8')",
           "        buf += struct.pack('<I', len(data)) + data",
           "    elif kind == 'str[]':",
           "        buf += struct.pack('<I', len(value))",
           "        for s in value:",
           "            _put(buf, 'str', s)",
           "    elif kind.endswith('[]'):",
           "        a = np.ascontiguousarray(np.asarray(value).reshape(-1), dtype=_NP[kind[:-2]])",
           "        buf += struct.pack('<I', a.size) + a.tobytes()",
           "    else:",
           "        buf += struct.pack('<' + _ST[kind], value)", "", "",
           "def _get(data: memoryview, at: int, kind: str):",
           "    if kind == 'str':",
           "        (n,) = struct.unpack_from('<I', data, at)",
           "        return bytes(data[at + 4:at + 4 + n]).decode('utf-8'), at + 4 + n",
           "    if kind == 'str[]':",
           "        (n,) = struct.unpack_from('<I', data, at)",
           "        at += 4",
           "        items = []",
           "        for _ in range(n):",
           "            s, at = _get(data, at, 'str')",
           "            items.append(s)",
           "        return items, at",
           "    if kind.endswith('[]'):",
           "        (n,) = struct.unpack_from('<I', data, at)",
           "        dtype = np.dtype(_NP[kind[:-2]])",
           "        end = at + 4 + n * dtype.itemsize",
           "        if end > len(data):",
           "            raise WireError('truncated message')",
           "        return np.frombuffer(data[at + 4:end], dtype=dtype).copy(), end",
           "    fmt = '<' + _ST[kind]",
           "    return struct.unpack_from(fmt, data, at)[0], at + struct.calcsize(fmt)", "", "",
           f"_ST = {PY_STRUCT!r}", f"_NP = {NP_DTYPE!r}", "", ""]
    for m in schema["messages"]:
        out.append("@dataclass")
        out.append(f"class {m['name']}:")
        out.append(f'    """{m["doc"]}"""')
        out.append(f"    TYPE = {m['type']}")
        out.append(f"    FIELDS = {[(n, t) for n, t, _ in fields(m)]!r}")
        for n, t, doc in fields(m):
            comment = f"  # {doc}" if doc else ""
            if t == "str":
                out.append(f"    {n}: str = ''{comment}")
            elif t == "str[]":
                out.append(f"    {n}: list = field(default_factory=list){comment}")
            elif t.endswith("[]"):
                out.append(f"    {n}: np.ndarray = field(default_factory=lambda: np.zeros(0, '{NP_DTYPE[t[:-2]]}')){comment}")
            elif t.startswith("f"):
                out.append(f"    {n}: float = 0.0{comment}")
            else:
                out.append(f"    {n}: int = 0{comment}")
        out.append("")
        out.append("    def encode(self) -> bytes:")
        out.append("        payload = bytearray()")
        out.append("        for name, kind in self.FIELDS:")
        out.append("            _put(payload, kind, getattr(self, name))")
        out.append("        return HEADER.pack(MAGIC, VERSION, self.TYPE, len(payload)) + bytes(payload)")
        out.append("")
        out.append("")
    names = ", ".join(f"{m['type']}: {m['name']}" for m in schema["messages"])
    out += [f"MESSAGES = {{{names}}}", "", "",
            "def decode(data: bytes):",
            '    """Decodes one message (header + payload) into its dataclass."""',
            "    view = memoryview(data)",
            "    if len(view) < HEADER.size:",
            "        raise WireError('message shorter than its header')",
            "    magic, version, kind, length = HEADER.unpack_from(view, 0)",
            "    if magic != MAGIC or version != VERSION:",
            "        raise WireError(f'bad magic / version {magic:#x} / {version}')",
            "    if HEADER.size + length != len(view):",
            "        raise WireError('length mismatch')",
            "    cls = MESSAGES.get(kind)",
            "    if cls is None:",
            "        raise WireError(f'unknown message type {kind}')",
            "    values, at = {}, HEADER.size",
            "    for name, k in cls.FIELDS:",
            "        values[name], at = _get(view, at, k)",
            "    if at != len(view):",
            "        raise WireError('trailing bytes after the message')",
            "    return cls(**values)"]
    return "\n".join(out) + "\n"


open(os.path.join(ROOT, "Sources/MotionIO/StreamMessages.swift"), "w").write(swift())
open(os.path.join(ROOT, "python/retargeter_client/messages.py"), "w").write(python())
print("wrote StreamMessages.swift and messages.py")
